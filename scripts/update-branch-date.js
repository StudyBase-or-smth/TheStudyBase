// scripts/update-branch-date.js
//
// Pre-commit updater for the header branch badge. Writes both
// BranchVersion.json and BranchVersion.js so file:// and http stay in sync.
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'BranchVersion.json');
const jsPath = path.join(root, 'BranchVersion.js');

const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
const now = new Date();
data.date = `${now.getDate()}-${now.getMonth() + 1}-${String(now.getFullYear()).slice(-2)}`;

try {
  const branch = execSync('git rev-parse --abbrev-ref HEAD', {
    cwd: root,
    encoding: 'utf8',
  }).trim();
  if (branch && branch !== 'HEAD') data.branch = branch;
} catch (e) {
  // keep existing branch label if git is unavailable
}

fs.writeFileSync(jsonPath, JSON.stringify(data, null, 2) + '\n');
fs.writeFileSync(
  jsPath,
  '// Auto-generated by scripts/update-branch-date.js - do not edit directly.\n' +
    '// Mirrors BranchVersion.json for pages opened via file:// (see comment there).\n' +
    'window.BRANCH_VERSION = ' + JSON.stringify(data, null, 2) + ';\n'
);
